#!/usr/bin/env python3
"""Write the catalogue of tile types for the add-on (Kotlin) and the editor (TypeScript).

The source is catalogue/<domain>.yaml plus catalogue/_kinds.yaml. Run after changing one; `--check` fails when
the generated files are stale (CI runs it).
"""
import json
import pathlib
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "catalogue"
KT = ROOT / "shared/src/main/kotlin/tech/shaffersoftworks/remotescreens/shared/Catalogue.kt"
TS = ROOT / "editor/src/generated/catalogue.ts"

HEADER = "Generated by tools/generate_catalogue.py from catalogue/*.yaml. Do not edit."


def word(v):
    """YAML 1.1 reads a bare on/off as a boolean; the catalogue always means the word."""
    if v is True:
        return "on"
    if v is False:
        return "off"
    return v


BOOLEAN_FIELDS = {"toggle", "confirm", "needs_entity"}


def clean(v, key=None):
    if isinstance(v, dict):
        return {str(word(k)): clean(x, str(word(k))) for k, x in v.items()}
    if isinstance(v, list):
        return [clean(x) for x in v]
    if key in BOOLEAN_FIELDS:
        return v
    return word(v)


def load():
    types = {}
    for path in sorted(SRC.glob("*.yaml")):
        if path.name.startswith("_"):
            continue
        spec = clean(yaml.safe_load(path.read_text()))
        if spec["domain"] != path.stem:
            sys.exit(f"{path.name}: domain {spec['domain']} does not match the file name")
        types[spec["domain"]] = spec
    kinds = clean(yaml.safe_load((SRC / "_kinds.yaml").read_text()))["kinds"]
    for key, spec in kinds.items():
        spec = dict(spec, domain=key)
        spec.setdefault("needs_entity", False)
        types[key] = spec
    for key, spec in types.items():
        for verb, action in spec.get("actions", {}).items():
            if "." not in action["service"]:
                sys.exit(f"{key}.{verb}: service must be domain.service")
        for verb in spec.get("predict", {}):
            if verb not in spec.get("actions", {}):
                sys.exit(f"{key}: predict names {verb}, which is not an action")
        if spec.get("tap") == "action" and spec.get("default_verb") not in spec.get("actions", {}):
            sys.exit(f"{key}: tap is action but default_verb is not an action")
    return types


def kt_value(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, list):
        return "listOf(" + ", ".join(kt_value(x) for x in v) + ")"
    if isinstance(v, dict):
        return "mapOf(" + ", ".join(f"{kt_str(k)} to {kt_value(x)}" for k, x in v.items()) + ")"
    return kt_str(v)


def kt_str(s):
    return json.dumps(str(s)).replace("$", "\\$")


def kotlin(types):
    out = [
        f"// {HEADER}",
        '@file:Suppress("MaxLineLength", "LargeClass")',
        "",
        "package tech.shaffersoftworks.remotescreens.shared",
        "",
        "object Catalogue {",
        "    val types: Map<String, TypeSpec> = mapOf(",
    ]
    for key, s in types.items():
        actions = ", ".join(
            f"{kt_str(v)} to ActionSpec({kt_str(a['service'])}, {kt_value(a.get('data', {}))}, {kt_value(a.get('confirm', False))}, {kt_str(a['relative']) if 'relative' in a else 'null'})"
            for v, a in s.get("actions", {}).items()
        )
        predict = ", ".join(
            f"{kt_str(v)} to PredictSpec({kt_str(p['state']) if 'state' in p else 'null'}, {kt_value({k: str(x) for k, x in p.get('attributes', {}).items()})})"
            for v, p in s.get("predict", {}).items()
        )
        fields = [
            f"domain = {kt_str(key)}",
            f"name = {kt_str(s['name'])}",
            f"icon = {kt_str(s['icon'])}",
            f"iconOn = {kt_str(s['icon_on']) if 'icon_on' in s else 'null'}",
            f"toggle = {kt_value(s.get('toggle', False))}",
            f"onStates = {kt_value(s.get('on_states', []))}",
            f"tap = {kt_str(s.get('tap', 'card'))}",
            f"defaultVerb = {kt_str(s['default_verb']) if 'default_verb' in s else 'null'}",
            f"card = {kt_str(s.get('card', 'none'))}",
            f"controls = {kt_value(s.get('controls', []))}",
            f"sizes = {kt_value(s.get('sizes', ['1x1']))}",
            f"options = {kt_value(s.get('options', []))}",
            f"actions = mapOf({actions})",
            f"predict = mapOf({predict})",
            f"needsEntity = {kt_value(s.get('needs_entity', True))}",
        ]
        out.append(f"        {kt_str(key)} to TypeSpec(")
        out += [f"            {f}," for f in fields]
        out.append("        ),")
    out += ["    )", "", "    fun of(kind: String?): TypeSpec? = types[kind]", "}", ""]
    return "\n".join(out)


def typescript(types):
    data = {}
    for key, s in types.items():
        data[key] = {
            "name": s["name"],
            "icon": s["icon"],
            "iconOn": s.get("icon_on"),
            "toggle": s.get("toggle", False),
            "tap": s.get("tap", "card"),
            "card": s.get("card", "none"),
            "controls": s.get("controls", []),
            "sizes": s.get("sizes", ["1x1"]),
            "options": s.get("options", []),
            "verbs": list(s.get("actions", {}).keys()),
            "needsEntity": s.get("needs_entity", True),
        }
    body = json.dumps(data, indent=2, ensure_ascii=False)
    return (
        f"// {HEADER}\n"
        "export interface TypeSpec {\n  name: string\n  icon: string\n  iconOn: string | null\n  toggle: boolean\n"
        "  tap: string\n  card: string\n  controls: string[]\n  sizes: string[]\n  options: string[]\n  verbs: string[]\n"
        "  needsEntity: boolean\n}\n\n"
        f"export const CATALOGUE: Record<string, TypeSpec> = {body}\n"
    )


def main():
    check = "--check" in sys.argv
    types = load()
    outputs = {KT: kotlin(types), TS: typescript(types)}
    stale = []
    for path, text in outputs.items():
        if check:
            if not path.exists() or path.read_text() != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if stale:
        sys.exit("stale, run tools/generate_catalogue.py: " + ", ".join(stale))
    if not check:
        print(f"{len(types)} types -> {KT.relative_to(ROOT)}, {TS.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
