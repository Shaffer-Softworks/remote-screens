package tech.shaffersoftworks.remotescreens.detekt

import dev.detekt.api.Config
import dev.detekt.api.RequiresAnalysisApi
import dev.detekt.api.Rule
import dev.detekt.api.RuleName
import dev.detekt.api.modifiedText
import org.jetbrains.kotlin.analysis.api.analyze
import org.jetbrains.kotlin.analysis.api.resolution.singleFunctionCallOrNull
import org.jetbrains.kotlin.psi.KtCallExpression
import org.jetbrains.kotlin.psi.KtFile
import org.jetbrains.kotlin.psi.KtLambdaArgument
import org.jetbrains.kotlin.psi.KtValueArgument

/**
 * Names every argument on a call that already has to be named.
 * [dev.detekt.rules.complexity.NamedArguments] reports these once type resolution is on.
 */
class NameCallArgumentsRule(config: Config) : Rule(
    config,
    "Calls with more than two arguments name every argument.",
), RequiresAnalysisApi {
    override val ruleName: RuleName = RuleName("NameCallArguments")

    private val insertions = mutableListOf<NameInsertion>()

    override fun preVisit(root: KtFile) {
        insertions.clear()
    }

    override fun postVisit(root: KtFile) {
        if (!autoCorrect || insertions.isEmpty()) {
            return
        }

        val corrected = StringBuilder(root.text)

        insertions.sortedByDescending { it.offset }.forEach { insertion ->
            corrected.insert(insertion.offset, insertion.text)
        }

        root.modifiedText = corrected.toString()
    }

    override fun visitCallExpression(expression: KtCallExpression) {
        super.visitCallExpression(expression)

        if (!autoCorrect || isGeneratedCatalogue(expression)) {
            return
        }

        val arguments = expression.valueArguments.filter { argument -> argument !is KtLambdaArgument }

        if (arguments.size <= ALLOWED_ARGUMENTS || arguments.all { it.isNamed() }) {
            return
        }

        val names = parameterNames(expression, arguments) ?: return

        arguments.zip(names).forEach { (argument, name) ->
            if (!argument.isNamed()) {
                insertions += NameInsertion(argument.textRange.startOffset, "${render(name)} = ")
            }
        }
    }

    private fun parameterNames(expression: KtCallExpression, arguments: List<KtValueArgument>): List<String>? =
        analyze(expression) {
            val call = expression.resolveToCall()?.singleFunctionCallOrNull() ?: return@analyze null

            @Suppress("DEPRECATION")
            val symbol = call.partiallyAppliedSymbol.signature.symbol

            if (!symbol.hasStableParameterNames) {
                return@analyze null
            }

            val mapping = call.valueArgumentMapping
            val namesAParameterMoreThanOnce = mapping.values
                .groupingBy { it.name.asString() }
                .eachCount()
                .any { (_, count) -> count > 1 }
            val passesAVararg = symbol.valueParameters.any { it.isVararg } ||
                mapping.values.any { it.symbol.isVararg }

            if (namesAParameterMoreThanOnce || passesAVararg) {
                return@analyze null
            }

            arguments.map { argument ->
                val argumentExpression = argument.getArgumentExpression() ?: return@analyze null
                call.valueArgumentMapping[argumentExpression]?.name?.asString() ?: return@analyze null
            }
        }

    private fun isGeneratedCatalogue(expression: KtCallExpression): Boolean {
        val file = expression.containingKtFile
        val path = file.virtualFile?.path.orEmpty()

        return file.name == GENERATED_CATALOGUE ||
            path.endsWith("/$GENERATED_CATALOGUE") ||
            file.text.startsWith(GENERATED_HEADER)
    }

    private data class NameInsertion(val offset: Int, val text: String)

    private companion object {
        const val ALLOWED_ARGUMENTS: Int = 2
        const val GENERATED_CATALOGUE: String = "Catalogue.kt"
        const val GENERATED_HEADER: String = "// Generated by tools/generate_catalogue.py"

        val HARD_KEYWORDS: Set<String> = setOf(
            "as",
            "break",
            "class",
            "continue",
            "do",
            "else",
            "false",
            "for",
            "fun",
            "if",
            "in",
            "interface",
            "is",
            "null",
            "object",
            "package",
            "return",
            "super",
            "this",
            "throw",
            "true",
            "try",
            "typealias",
            "typeof",
            "val",
            "var",
            "when",
            "while",
        )

        fun render(name: String): String = if (name in HARD_KEYWORDS) "`$name`" else name
    }
}
