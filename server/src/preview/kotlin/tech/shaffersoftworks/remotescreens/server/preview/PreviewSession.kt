/** Owns output and coverage shared by the light and dark scenario sessions. */
internal class PreviewOutput(private val directory: File, private val filter: String) {
    private val assets = File(directory, "assets/documents").apply { mkdirs() }
    private val entries = mutableListOf<String>()
    val covered = linkedSetOf<String>()
    private var count = 0

    init {
        assets.listFiles()?.filter { it.extension == "rc" }?.forEach { check(it.delete()) }
    }

    fun emit(group: String, label: String, device: Device, input: RenderInput, render: () -> RenderedDoc) {
        val filename = "${count++}.rc"
        runCatching {
            File(assets, filename).writeBytes(snapshot(render(), input.states))
        }.getOrElse { failure ->
            throw IllegalStateException("Preview failed: $group / $label", failure)
        }
        if ("$group $label".contains(filter, ignoreCase = true)) {
            val arguments = listOf(group, label, "documents/$filename").joinToString { Json.encodeToString(it) }
            entries += "        PreviewCase($arguments, ${device.widthDp}, ${device.heightDp}),"
        }
    }

    fun finish() {
        validateCoverage(covered)
        check(entries.isNotEmpty()) { "No preview matches previewFilter=$filter" }
        val source = File(directory, "kotlin/tech/shaffersoftworks/remotescreens/preview/GeneratedPreviews.kt")
        source.parentFile.mkdirs()
        source.writeText(
            "// Generated by :server:generatePreviews. Do not edit.\n" +
                "package tech.shaffersoftworks.remotescreens.preview\n\n" +
                "internal val generatedPreviews = listOf(\n" + entries.joinToString("\n") + "\n)\n",
        )
        File(directory, "coverage.txt").writeText(covered.sorted().joinToString("\n") + "\n")
        println("Generated $count Remote Compose previews; ${entries.size} selected; ${covered.size} coverage entries.")
    }
}

internal data class PreviewEnvironment(
    val originalStates: Map<String, EntityState>,
    val config: HomeAssistantConfig,
    val data: RenderData,
    val demo: Screen,
    val extraPages: List<Page>,
)

internal data class PageCanvas(
    val chrome: Boolean = false,
    val device: Device = Device(WALL_WIDTH, WALL_HEIGHT, 1f),
    val grid: GridSize = GridSize(1, 1),
)

/** Shared render fixtures for one palette; scenario files only describe variations. */
internal class PreviewSession(
    val output: PreviewOutput,
    val themeName: String,
    val palette: Palette,
    private val environment: PreviewEnvironment,
) {
    val originalStates get() = environment.originalStates
    val data get() = environment.data
    val demo get() = environment.demo
    val extraPages get() = environment.extraPages
    val wall = Device(WALL_WIDTH, WALL_HEIGHT, 1f)
    private val i18n = I18n("en", I18n.load("en"), emptyMap(), true)

    fun input(
        states: Map<String, EntityState> = originalStates,
        renderData: RenderData = data,
        intercom: IntercomView = IntercomView(
            true,
            "Ready to call",
            false,
            null,
            listOf(IntercomStation("kitchen", "Kitchen"), IntercomStation("bedroom", "Bedroom")),
        ),
    ) = RenderInput(
        states,
        i18n,
        environment.config,
        renderData,
        palette,
        supportsCalendarDialogs = true,
        intercom = intercom,
    )

    fun emit(
        group: String,
        label: String,
        renderInput: RenderInput = input(),
        device: Device = wall,
        render: () -> RenderedDoc,
    ) = output.emit(group, "$label · $themeName", device, renderInput, render)

    fun page(
        group: String,
        label: String,
        page: Page,
        renderInput: RenderInput = input(),
        canvas: PageCanvas = PageCanvas(),
    ) {
        val screen = previewScreen(page, canvas.chrome, canvas.grid.cols, canvas.grid.rows)
        emit(group, label, renderInput, canvas.device) {
            ScreenRenderer.render(screen, canvas.device, renderInput)
        }
    }
}
